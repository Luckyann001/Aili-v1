// Plain labels with no schema library, so the web app can import them without bundling Zod.
export type ReviewStatusName = "draft" | "reviewed" | "published";

/** What a learner sees for each review status. Drafts are always labelled as such. */
export const REVIEW_LABEL: Record<ReviewStatusName, string> = {
  draft: "Draft (not expert-reviewed)",
  reviewed: "Reviewed",
  published: "Published",
};

/** What the label function needs to know about an item: never more than its own record says. */
export interface LabelledItem {
  fidelity: "verified" | "simplified_teaching" | "illustrative";
  provenance: "authored" | "commissioned" | "open_licensed" | "ai_composed" | "ai_generated";
  review_status?: ReviewStatusName;
  review?: { role?: "founder" | "expert" };
  test_fixture?: true;
}

/**
 * The one visible label for a scene or asset, derived from its fidelity, provenance and review record
 * (replaces the hard-coded "Illustrative (AI-composed)"). AI composition is named only when the
 * provenance says so; a founder review is never passed off as an expert one. `label` is the short
 * text; `detail` says the rest (for a tooltip or screen readers).
 */
export function contentLabel(item: LabelledItem): { label: string; detail: string } {
  const made =
    item.provenance === "ai_composed" ? "Illustrative (AI-composed)"
    : item.provenance === "ai_generated" ? "Illustrative (AI-generated)"
    : item.fidelity === "verified" ? "Verified model"
    : item.fidelity === "simplified_teaching" ? "Simplified teaching model"
    : "Illustrative · generic, not measured";
  const fidelity = { verified: "verified model", simplified_teaching: "simplified teaching model", illustrative: "illustrative, not measured" }[item.fidelity];
  const source = { authored: "made by Aili's authors", commissioned: "commissioned", open_licensed: "openly licensed", ai_composed: "composed by AI from library parts", ai_generated: "generated by AI" }[item.provenance];
  const detail = `${fidelity[0]!.toUpperCase()}${fidelity.slice(1)}; ${source}.`;
  const reviewed = item.review && item.review_status !== "draft";
  if (reviewed && item.review!.role === "founder") return { label: "Prepared · reviewed by the founder, not an expert reviewer", detail: `${made}. ${detail}` };
  if (reviewed) return { label: `${made} · expert-reviewed`, detail };
  return { label: made, detail };
}
